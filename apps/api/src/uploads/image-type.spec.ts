import { detectImage, STORED_NAME } from "./image-type.js";

const pad = (bytes: number[]) => Buffer.concat([Buffer.from(bytes), Buffer.alloc(16)]);

describe("detectImage", () => {
  it("recognizes jpeg, png and webp by their content", () => {
    expect(detectImage(pad([0xff, 0xd8, 0xff, 0xe0]))?.ext).toBe("jpg");
    expect(detectImage(pad([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))?.ext).toBe("png");
    expect(detectImage(Buffer.from("RIFF0000WEBPVP8 rest", "ascii"))?.ext).toBe("webp");
  });

  it("rejects files that only claim to be images", () => {
    expect(
      detectImage(Buffer.from("<svg xmlns='http://www.w3.org/2000/svg'></svg>")),
    ).toBeUndefined();
    expect(detectImage(Buffer.from("GIF89a................"))).toBeUndefined();
  });
});

describe("STORED_NAME", () => {
  it("only accepts names generated by the server", () => {
    expect(STORED_NAME.test("3f2b8c1e-1d2a-4c8e-9a0b-123456789abc.webp")).toBe(true);
    expect(STORED_NAME.test("../.env")).toBe(false);
    expect(STORED_NAME.test("foto.jpg")).toBe(false);
  });
});
